use liaise::{Liaise, LiaiseCodes};
use std::error::Error as _;

#[derive(Debug, LiaiseCodes)]
#[liaise(prefix = "SRC")]
enum Code {
    #[liaise(code = 1, msg = "I/O failure", source)]
    Io(std::io::Error),
    #[liaise(code = 2, msg = "parse failure", source)]
    Parse(std::num::ParseIntError),
    #[liaise(code = 3, msg = "refused")]
    Refused,
}

fn read_number(text: &str) -> Result<i32, Code> {
    let n: i32 = text.trim().parse()?; // From<ParseIntError> is generated by `source`
    if n < 0 { return Err(Code::Refused); }
    Ok(n)
}

#[test]
fn source_lifts_the_inner_error_through_from_and_question_mark() {
    let err = read_number("x").unwrap_err();
    assert_eq!(err.code_id(), 2);
    assert!(matches!(err, Code::Parse(_)));
}

#[test]
fn source_is_reported_by_error_source() {
    let io = std::io::Error::new(std::io::ErrorKind::Other, "disk");
    let err: Code = io.into();
    assert_eq!(err.code_id(), 1);
    let inner = err.source().expect("source variant exposes the inner error");
    assert_eq!(inner.to_string(), "disk");
    assert!(Code::Refused.source().is_none(), "a variant without `source` has none");
}
